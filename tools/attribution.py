"""Write ATTRIBUTION.md from assets/memes/manifest.json and make docs/social.png from the hero screenshot."""
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
man = json.loads((ROOT / "assets" / "memes" / "manifest.json").read_text(encoding="utf-8"))

rows = []
for stem, m in sorted(man.items(), key=lambda kv: kv[1]["name"].lower()):
    src = m["source"]
    host = "Imgflip template" if "imgflip" in src else "Know Your Meme entry image"
    rows.append(f"| `{stem}.jpg` | {m['name']} | [{host}]({src}) |")

text = f"""# Image attribution

MemeOS ships {len(man)} well-known meme pictures as the seed contents of the virtual `~/Memes` folder and as
illustrations in the README, the achievements and a few easter eggs. They are downscaled to at most 900 px and
re-encoded. They are used as small, non-commercial illustrations in the tradition of meme reuse; MemeOS claims no
rights to any of them and they are not needed for the operating system itself to work. If you hold rights to one of
them and want it removed, open an issue and it will be taken down.

Sources: the Imgflip meme template images (`imgflip.com/s/meme/<Name>.jpg`) and the entry images on Know Your Meme.
Rights stay with the original creators and publishers: Doge is a photo of Kabosu by Atsuko Sato; Pepe the Frog is a
character by Matt Furie; Nyan Cat by Christopher Torres; film and TV stills belong to their studios; and so on.

| File | Meme | Source |
|---|---|---|
""" + "\n".join(rows) + """

The wallpapers in `assets/wallpapers/` are generated by `tools/make_wallpapers.py` and the logo, avatars and icons in
`assets/` and `js/core/icons.js` are original drawings for this project (MIT, like the code).

The rendered README images in `docs/readme/` are screenshots of MemeOS and therefore contain some of the pictures above.
"""
(ROOT / "ATTRIBUTION.md").write_text(text, encoding="utf-8")
print("ATTRIBUTION.md", len(rows), "rows")

# social preview: 1280x640 crop of the hero shot with a title plate
hero = Image.open(ROOT / "docs" / "readme" / "hero.png").convert("RGB")
w, h = hero.size
crop = hero.crop((0, 0, w, w // 2)).resize((1280, 640), Image.LANCZOS)
d = ImageDraw.Draw(crop, "RGBA")
d.rectangle((0, 470, 1280, 640), fill=(10, 11, 16, 215))
logo = Image.open(ROOT / "docs" / "logo-128.png").convert("RGBA") if (ROOT / "docs" / "logo-128.png").exists() else None
try:
    f1 = ImageFont.truetype("C:/Windows/Fonts/segoeuib.ttf", 54); f2 = ImageFont.truetype("C:/Windows/Fonts/segoeui.ttf", 24)
except OSError:
    f1 = f2 = ImageFont.load_default()
d.text((48, 492), "MemeOS", font=f1, fill=(255, 255, 255))
d.text((50, 566), "A desktop operating system that runs in one browser tab. Much window. Very file. Wow.", font=f2, fill=(190, 194, 208))
crop.save(ROOT / "docs" / "social.png", optimize=True)
print("docs/social.png", crop.size)
